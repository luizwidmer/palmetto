void test_bcpack_refusals() {
    using palmetto::dstorage::bcpack::DecodeError;
    using palmetto::dstorage::bcpack::decode;
    const EncoderVector* base = nullptr;
    const EncoderVector* two_blocks = nullptr;
    for (const EncoderVector& vector : kEncoderVectors) {
        if (vector.codec == 1 && vector.blocks == 1) base = &vector;
        if (vector.codec == 1 && vector.blocks == 2) two_blocks = &vector;
    }
    check(base != nullptr, "bcpack refusals: a one-block BC1 vector exists");
    if (base == nullptr) return;
    std::vector<unsigned char> destination(8);
    check(decode(2, base->source, base->source_size, destination.data(), 16, nullptr, nullptr) == DecodeError::codec,
          "bcpack: BC2 has no block rebuilder (codec)");
    check(decode(1, base->source, base->source_size, destination.data(), 7, nullptr, nullptr) ==
              DecodeError::destination_size,
          "bcpack: a destination that is not whole blocks is refused");
    check(decode(1, base->source, base->source_size, nullptr, 8, nullptr, nullptr) == DecodeError::bounds,
          "bcpack: a null destination is refused");
    check(decode(1, base->source, base->source_size, destination.data(), 0, nullptr, nullptr) ==
              DecodeError::destination_size,
          "bcpack: a source with an empty destination is refused");
    check(decode(1, nullptr, 0, destination.data(), 0, nullptr, nullptr) == DecodeError::ok,
          "bcpack: nothing to decode is ok");
    std::vector<unsigned char> truncated(base->source, base->source + base->source_size / 2);
    std::vector<unsigned char> wide(64);
    check(decode(1, truncated.data(), truncated.size(), wide.data(), wide.size(), nullptr, nullptr) != DecodeError::ok,
          "bcpack: a truncated chunk is refused");
    std::vector<unsigned char> trailing(base->source, base->source + base->source_size);
    trailing.push_back(0xAA);
    check(decode(1, trailing.data(), trailing.size(), wide.data(), wide.size(), nullptr, nullptr) != DecodeError::ok,
          "bcpack: non-zero bytes after the last lane are refused");
    if (two_blocks != nullptr)
        check(decode(1, two_blocks->source, two_blocks->source_size, destination.data(), destination.size(), nullptr,
                     nullptr) != DecodeError::ok,
              "bcpack: a destination smaller than the stream is refused");
}

std::string bc1_predictor_json(const unsigned (&row)[6]) {
    return "{\"codec\":\"bc1\",\"confirmed\":{\"255\":[" + std::to_string(row[0]) + "," + std::to_string(row[1]) +
           "," + std::to_string(row[2]) + "," + std::to_string(row[3]) + "," + std::to_string(row[4]) + "," +
           std::to_string(row[5]) + "]},\"provisional\":{\"254\":[1,2,3,4,5,6]}}";
}

void test_bcpack_history(const testfiles::ScratchDir& scratch) {
    using palmetto::dstorage::bcpack::DecodeError;
    using palmetto::dstorage::bcpack::decode;
    const std::filesystem::path file = scratch.path() / L"bc1_history.json";
    const unsigned row[6] = {7, 13, 21, 3, 9, 17};
    write_file(file, bc1_predictor_json(row));
    BcpackHistory history;
    PredictorReport report;
    check_predictor(load_dstorage_predictor(file.wstring().c_str(), report, &history), PredictorError::ok,
                    "bcpack history: a BC1-only predictor file loads");
    check(report.bc1_rows == 1 && history.bc1_present && history.bc1_class[255] == 3,
          "bcpack history: the confirmed BC1 row is retained as class 3");
    check(history.bc1_class[254] == 1, "bcpack history: the provisional BC1 row is retained as class 1");
    bool retained = true;
    for (unsigned i = 0; i < 6; ++i) retained = retained && history.bc1[255][i] == row[i];
    check(retained, "bcpack history: the BC1 row values are retained");
    check(!history.bc6h_present && report.bc6h_endpoint_rows == 0,
          "bcpack history: a BC1-only file reports no BC6H section");

    // Block 0 with distance 1 (lane 0 symbol zig(1) = 2) predicts its endpoints from row 255 and adds these deltas.
    const int delta[6] = {1, -2, 3, -1, 2, -3};
    static constexpr unsigned kMods[6] = {32, 64, 32, 32, 64, 32};
    unsigned endpoint[6];
    for (unsigned i = 0; i < 6; ++i) {
        int value = (static_cast<int>(row[i]) + delta[i]) % static_cast<int>(kMods[i]);
        if (value < 0) value += static_cast<int>(kMods[i]);
        endpoint[i] = static_cast<unsigned>(value);
    }
    std::vector<std::vector<unsigned>> lanes(12);
    for (auto& lane : lanes) lane = {0};
    lanes[0][0] = 2;
    for (unsigned i = 0; i < 6; ++i) lanes[2 + i][0] = zigzag(delta[i]);
    const std::vector<unsigned char> chunk = TestEncoder::encode(lanes, 1);
    check(!chunk.empty(), "bcpack history: the test encoder built the history chunk");
    unsigned char expected[8];
    const unsigned c0 = (endpoint[0] << 11) | (endpoint[1] << 5) | endpoint[2];
    const unsigned c1 = (endpoint[3] << 11) | (endpoint[4] << 5) | endpoint[5];
    expected[0] = static_cast<unsigned char>(c0);
    expected[1] = static_cast<unsigned char>(c0 >> 8);
    expected[2] = static_cast<unsigned char>(c1);
    expected[3] = static_cast<unsigned char>(c1 >> 8);
    expected[4] = expected[5] = expected[6] = expected[7] = 0xAA;  // kQuad1[0]
    unsigned char out[8] = {};
    palmetto::dstorage::bcpack::DecodeStats stats;
    check(decode(1, chunk.data(), chunk.size(), out, sizeof out, &history, &stats) == DecodeError::ok &&
              std::memcmp(out, expected, sizeof out) == 0 && stats.history_reads != 0,
          "bcpack history: a block reading a confirmed built-in row decodes from the predictor");
    unsigned char refused[8] = {};
    check(decode(1, chunk.data(), chunk.size(), refused, sizeof refused, nullptr, nullptr) ==
              DecodeError::history_unknown,
          "bcpack history: the same block without a predictor is refused by name");
    BcpackHistory provisional_only;
    provisional_only.bc1_present = true;
    provisional_only.bc1_class[255] = 1;
    for (unsigned i = 0; i < 6; ++i) provisional_only.bc1[255][i] = static_cast<std::uint8_t>(row[i]);
    check(decode(1, chunk.data(), chunk.size(), refused, sizeof refused, &provisional_only, nullptr) ==
              DecodeError::history_unconfirmed,
          "bcpack history: a fitted-only built-in row is refused by name");

    // A BC6H chunk (mode 11) that reads built-in endpoint history entry 255: refused when the predictor confirms no
    // bits of the row, accepted once it confirms every field the mode reads.
    std::vector<std::vector<unsigned>> bc6h(16);
    for (auto& lane : bc6h) lane = {0, 0};
    const auto distance = deint4(zigzag(1));
    bc6h[0] = {distance.first, distance.second};  // di = 0, so de = 1 -> entry 255
    bc6h[15] = {10, 0};                           // mode 11 (1 region)
    for (unsigned row_index = 0; row_index < 4; ++row_index) {
        // zero index state is 8; a -8 delta (zig 15) lands every index on 0 and keeps the anchors clear
        const unsigned packed = pack_index_pair(15, 15, row_index);
        bc6h[11 + row_index] = {packed, packed};
    }
    const std::vector<unsigned char> bc6h_chunk = TestEncoder::encode(bc6h, 6);
    check(!bc6h_chunk.empty(), "bcpack history: the test encoder built the BC6H history chunk");
    BcpackHistory bc6h_history;
    bc6h_history.bc6h_present = true;
    bc6h_history.bc6h_endpoint_class[255] = 3;
    for (unsigned c = 0; c < 3; ++c)
        for (unsigned q = 0; q < 4; ++q)
            bc6h_history.bc6h_endpoint[255][c][q] = static_cast<std::uint16_t>(0x100 + q);
    unsigned char wide[16] = {};
    check(decode(6, bc6h_chunk.data(), bc6h_chunk.size(), wide, sizeof wide, &bc6h_history, nullptr) ==
              DecodeError::history_depth,
          "bcpack history: a confirmed BC6H row with no confirmed bits is refused (history_depth)");
    for (unsigned c = 0; c < 3; ++c) {
        bc6h_history.bc6h_endpoint_bits[255][c][0] = 16;
        bc6h_history.bc6h_endpoint_bits[255][c][1] = 10;
        bc6h_history.bc6h_endpoint_bits[255][c][2] = 10;
        bc6h_history.bc6h_endpoint_bits[255][c][3] = 10;
    }
    palmetto::dstorage::bcpack::DecodeStats bc6h_stats;
    check(decode(6, bc6h_chunk.data(), bc6h_chunk.size(), wide, sizeof wide, &bc6h_history, &bc6h_stats) ==
              DecodeError::ok && bc6h_stats.history_reads != 0,
          "bcpack history: the same BC6H chunk decodes once the predictor confirms the row's bits");

    // A BC7 mode-6 block that reads built-in endpoint history entry 255 (block 0, de = 1): unknown, unconfirmed and
    // confirmed are three distinct answers from the predictor, and only the last decodes.
    std::vector<std::vector<unsigned>> bc7(16);
    for (auto& lane : bc7) lane = {0, 0};
    bc7[0] = {distance.first, distance.second};
    const palmetto::dstorage::bcpack::Bc7Tables& tables = palmetto::dstorage::bcpack::bc7_tables();
    unsigned signature_a = 0;
    unsigned signature_b = 0;
    bool found_signature = false;
    for (unsigned a = 0; a < 32 && !found_signature; ++a)
        for (unsigned b = 0; b < 16 && !found_signature; ++b)
            if (tables.rank_of[a * 16 + b] >= 0 && tables.config[tables.rank_of[a * 16 + b]][0] == 6) {
                signature_a = a;
                signature_b = b;
                found_signature = true;
            }
    check(found_signature, "bcpack history: the mode-6 BC7 signature pair is in the table");
    bc7[15] = {signature_a, signature_b};
    const std::vector<unsigned char> bc7_chunk = TestEncoder::encode(bc7, 7);
    check(!bc7_chunk.empty(), "bcpack history: the test encoder built the BC7 history chunk");
    BcpackHistory bc7_history;
    bc7_history.bc7_present = true;
    for (std::size_t i = 0; i < 24; ++i) {
        bc7_history.bc7_endpoint[255][i] = 0x80;
        bc7_history.bc7_endpoint_bits[255][i] = 0;
        bc7_history.bc7_endpoint_confirmed[255][i] = 0;
    }
    check(decode(7, bc7_chunk.data(), bc7_chunk.size(), wide, 16, &bc7_history, nullptr) == DecodeError::history_unknown,
          "bcpack history: a BC7 row with no recorded depth is history_unknown");
    for (std::size_t i = 0; i < 24; ++i) bc7_history.bc7_endpoint_bits[255][i] = 8;
    check(decode(7, bc7_chunk.data(), bc7_chunk.size(), wide, 16, &bc7_history, nullptr) ==
              DecodeError::history_unconfirmed,
          "bcpack history: a BC7 row known but not confirmed is history_unconfirmed");
    for (std::size_t i = 0; i < 24; ++i) bc7_history.bc7_endpoint_confirmed[255][i] = 8;
    palmetto::dstorage::bcpack::DecodeStats bc7_stats;
    check(decode(7, bc7_chunk.data(), bc7_chunk.size(), wide, 16, &bc7_history, &bc7_stats) == DecodeError::ok &&
              bc7_stats.history_reads != 0,
          "bcpack history: the same BC7 chunk decodes once the predictor confirms the row");

    // A BC1 lane 1 that is not zero is a structural inconsistency, not a decodable block.
    std::vector<std::vector<unsigned>> bad_bc1(12);
    for (auto& lane : bad_bc1) lane = {0};
    bad_bc1[1][0] = 1;
    const std::vector<unsigned char> bad_bc1_chunk = TestEncoder::encode(bad_bc1, 1);
    check(decode(1, bad_bc1_chunk.data(), bad_bc1_chunk.size(), out, 8, nullptr, nullptr) == DecodeError::consistency,
          "bcpack: a non-zero BC1 lane 1 is refused (consistency)");

    // A BC1 row outside a channel's range is refused by the loader even though the previous loader never read it.
    const std::filesystem::path bad = scratch.path() / L"bc1_bad.json";
    write_file(bad, "{\"codec\":\"bc1\",\"confirmed\":{\"255\":[99,0,0,0,0,0]}}");
    PredictorReport bad_report;
    check_predictor(load_dstorage_predictor(bad.wstring().c_str(), bad_report), PredictorError::out_of_range,
                    "bcpack history: a BC1 row outside the channel range is out_of_range");
}


