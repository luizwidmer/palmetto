// ---- BCPack block decoder ------------------------------------------------------------------------------------------
//
// The test carries a small rANS encoder, the inverse of the runtime lane scheduler: it turns per-lane symbol lists into
// a BCPack chunk, so the decoder is exercised against streams built here as well as against the embedded reference
// chunks. The embedded chunks were produced by this project's Python implementation (tooling/bcpack.py) from synthetic
// lane symbols; the encoder's output must match them byte for byte, which pins this encoder and the runtime decoder to
// the same format. Every byte below was generated in the test or by that tooling - no game data.

std::uint32_t zigzag(int value) {
    return value < 0 ? static_cast<std::uint32_t>(-2 * value - 1) : static_cast<std::uint32_t>(2 * value);
}

std::pair<unsigned, unsigned> deint(unsigned value, unsigned bits) {
    std::pair<unsigned, unsigned> halves{0, 0};
    for (unsigned k = 0; k < bits; ++k) {
        halves.first |= ((value >> (2 * k)) & 1u) << k;
        halves.second |= ((value >> (2 * k + 1)) & 1u) << k;
    }
    return halves;
}

std::pair<unsigned, unsigned> deint4(unsigned value) { return deint(value, 4); }

// The 2x2 index pair the BC6H/BC7 row lanes carry for pixels (2k, 2k+1) of row y.
unsigned pack_index_pair(unsigned left, unsigned right, unsigned row) {
    return row < 3 ? palmetto::dstorage::bcpack::interleave(right, left, 4)
                   : palmetto::dstorage::bcpack::interleave(left, right, 4);
}

struct TestEncoder {
    using Model = palmetto::dstorage::bcpack::Model;
    using LanePhase = unsigned;
    static constexpr std::uint32_t kHome = palmetto::dstorage::bcpack::kRansHome;

    static void encode_symbols(const std::vector<unsigned>& symbols, const Model& model, std::uint32_t& state,
                               std::vector<unsigned char>& reversed) {
        for (auto it = symbols.rbegin(); it != symbols.rend(); ++it) {
            const unsigned symbol = *it;
            unsigned p = 0;
            for (unsigned value = symbol; value != 0; value >>= 1) ++p;
            std::uint32_t f = model.frequency[p];
            std::uint32_t c = model.base[p] + f * (symbol - (p == 0 ? 0u : 1u << (p - 1)));
            if (c == 0) {
                --f;
                ++c;
            }
            const std::uint32_t limit = f << 16;
            while (state >= limit) {
                reversed.push_back(static_cast<unsigned char>(state & 0xFF));
                state >>= 8;
            }
            const std::uint32_t quotient = state / f;
            state = (quotient << 16) + c + (state % f);
        }
    }

    static std::vector<unsigned char> header(unsigned default_width, unsigned width, unsigned q, std::size_t length) {
        const unsigned z = (default_width - width) & 3u;
        std::vector<unsigned char> bytes;
        if (length <= 256) {
            bytes.push_back(static_cast<unsigned char>((z << 6) | (1u << 4) | (q & 15u)));
            bytes.push_back(static_cast<unsigned char>(length - 1));
        } else {
            const unsigned extended = static_cast<unsigned>(length) - 257;
            bytes.push_back(static_cast<unsigned char>((z << 6) | (1u << 5) | (1u << 4) | (q & 15u)));
            bytes.push_back(static_cast<unsigned char>(extended & 0xFF));
            bytes.push_back(static_cast<unsigned char>((extended >> 8) & 0xFF));
        }
        return bytes;
    }

    // One flush fragment: four state bytes, the reverse-encoded bytes, and the zero bytes the format omits.
    static std::vector<unsigned char> fragment(const std::vector<unsigned>& symbols, unsigned default_width,
                                               unsigned q) {
        const Model& model = palmetto::dstorage::bcpack::model_for(default_width, q);
        std::uint32_t state = kHome;
        std::vector<unsigned char> reversed;
        encode_symbols(symbols, model, state, reversed);
        std::vector<unsigned char> payload = {static_cast<unsigned char>(state >> 24),
                                              static_cast<unsigned char>(state >> 16),
                                              static_cast<unsigned char>(state >> 8),
                                              static_cast<unsigned char>(state)};
        payload.insert(payload.end(), reversed.rbegin(), reversed.rend());
        unsigned stripped = 0;
        while (payload.size() > 1 && payload.back() == 0 && stripped < 8) {
            payload.pop_back();
            ++stripped;
        }
        std::vector<unsigned char> bytes = header(default_width, default_width, q, payload.size());
        bytes.insert(bytes.end(), payload.begin(), payload.end());
        return bytes;
    }

    // The byte-order scheduler of docs/textures.md section 2, as an encoder: one byte is taken from each requesting
    // lane in lane order, at most eight per cycle, and a lane that requested but was not served freezes for the cycle.
    // An empty result means the lane streams could not be interleaved (a test bug, not a format answer).
    static std::vector<unsigned char> interleave(const std::vector<std::vector<unsigned char>>& streams,
                                                 const unsigned* widths, unsigned lanes_used, std::size_t elements) {
        struct Lane {
            LanePhase phase = 0;  // 0 header, 1 length, 2 long length, 3 symbols
            const Model* model = nullptr;
            std::size_t position = 0;
            std::uint32_t previous = 0;
            std::uint32_t advanced = 0;
            std::size_t remaining = 0;
            std::size_t payload = 0;
            unsigned width = 0;
            unsigned byte = 0;
            unsigned symbol = 0;
            unsigned zeros = 0;
            bool flush = false;
            bool extended = false;
            bool buffered = false;
            bool held = false;
            bool full = false;
            bool done = false;
            bool stalled = false;
        };
        std::array<Lane, 16> lanes{};
        std::vector<unsigned char> out;
        for (unsigned i = 0; i < lanes_used; ++i) {
            lanes[i].remaining = elements;
            lanes[i].done = elements == 0;
        }
        for (std::size_t cycle = 0; cycle < 64 + 256 * elements + 4096; ++cycle) {
            bool all_done = true;
            for (unsigned i = 0; i < lanes_used; ++i)
                if (!(lanes[i].done && !lanes[i].full)) all_done = false;
            if (all_done) {
                for (unsigned i = 0; i < lanes_used; ++i)
                    if (lanes[i].position != streams[i].size()) return {};
                return out;
            }
            unsigned budget = 8;
            for (unsigned i = 0; i < lanes_used; ++i) {
                Lane& lane = lanes[i];
                if (lane.done || (lane.full && lane.held)) {
                    lane.stalled = true;
                    continue;
                }
                lane.stalled = false;
                if (lane.phase == 3)
                    lane.advanced = lane.held ? lane.model->advance(lane.previous, lane.symbol) : lane.previous;
                if (!lane.buffered && (lane.phase != 3 || lane.payload > 0)) {
                    if (budget == 0) {
                        lane.stalled = true;
                        continue;
                    }
                    if (lane.position >= streams[i].size()) return {};
                    lane.byte = streams[i][lane.position++];
                    lane.buffered = true;
                    out.push_back(static_cast<unsigned char>(lane.byte));
                    --budget;
                }
                if (lane.held) {
                    lane.full = true;
                    lane.held = false;
                }
            }
            for (unsigned i = 0; i < lanes_used; ++i) {
                Lane& lane = lanes[i];
                if (lane.done || lane.stalled) continue;
                if (lane.phase == 0) {
                    if (!lane.buffered) continue;
                    const unsigned header_byte = lane.byte;
                    lane.buffered = false;
                    lane.flush = (header_byte & 0x10u) != 0;
                    lane.extended = (header_byte & 0x20u) != 0;
                    lane.width = widths[i] - (header_byte >> 6);
                    lane.model = &palmetto::dstorage::bcpack::model_for(lane.width, header_byte & 15u);
                    lane.zeros = 0;
                    lane.phase = 1;
                } else if (lane.phase == 1) {
                    if (!lane.buffered) continue;
                    lane.payload = lane.extended ? lane.byte : lane.byte + 1u;
                    lane.buffered = false;
                    lane.phase = lane.extended ? 2 : 3;
                } else if (lane.phase == 2) {
                    if (!lane.buffered) continue;
                    lane.payload = (static_cast<std::size_t>(lane.byte) << 8) + (lane.payload & 0xFFu) + 257u;
                    lane.buffered = false;
                    lane.phase = 3;
                } else {
                    std::uint32_t state = lane.advanced;
                    if (state < kHome) {
                        if (lane.payload > 0) {
                            if (lane.buffered) {
                                state = (state << 8) | lane.byte;
                                lane.buffered = false;
                                --lane.payload;
                                if (lane.payload == 0 && lane.flush && state != 0)
                                    while (state < kHome && lane.zeros < 8) {
                                        state <<= 8;
                                        ++lane.zeros;
                                    }
                            }
                        } else if (lane.flush) {
                            if (state == 0 || lane.zeros >= 8) return {};
                            while (state < kHome && state != 0 && lane.zeros < 8) {
                                state <<= 8;
                                ++lane.zeros;
                            }
                        } else {
                            lane.previous = state;
                            if (lane.remaining > 0) {
                                lane.phase = 0;
                            } else {
                                lane.done = true;
                            }
                            continue;
                        }
                    }
                    const bool next_symbol = state > kHome && lane.remaining > 0;
                    if (next_symbol) {
                        lane.symbol = lane.model->symbol(state);
                        --lane.remaining;
                        if ((lane.symbol >> lane.width) != 0) return {};
                    }
                    lane.held = next_symbol;
                    lane.previous = state;
                    if (lane.payload == 0) {
                        if (lane.flush) {
                            if (state == kHome) {
                                if (lane.remaining > 0) {
                                    lane.phase = 0;
                                    lane.previous = 0;
                                    lane.advanced = 0;
                                } else {
                                    lane.done = true;
                                }
                            } else if (state > kHome && !next_symbol) {
                                return {};
                            }
                        } else if (lane.remaining == 0 && !next_symbol) {
                            lane.done = true;
                        } else if (state == kHome) {
                            return {};
                        }
                    } else if (state == kHome || (lane.remaining == 0 && !next_symbol && state > kHome)) {
                        return {};
                    }
                }
            }
            bool ready = true;
            bool any_full = false;
            for (unsigned i = 0; i < lanes_used; ++i) {
                if (lanes[i].full) {
                    any_full = true;
                } else if (!(lanes[i].done && !lanes[i].held)) {
                    ready = false;
                    break;
                }
            }
            if (ready && any_full)
                for (unsigned i = 0; i < lanes_used; ++i) lanes[i].full = false;
            for (unsigned i = 0; i < lanes_used; ++i)
                if (lanes[i].done && lanes[i].held && !lanes[i].full) {
                    lanes[i].full = true;
                    lanes[i].held = false;
                }
        }
        return {};
    }

    static std::vector<unsigned char> encode(const std::vector<std::vector<unsigned>>& lanes, unsigned codec) {
        const unsigned lanes_used = codec >= 6 ? 16u : 12u;
        const unsigned* widths = palmetto::dstorage::bcpack::kLaneWidths[codec];
        std::vector<std::vector<unsigned char>> streams(lanes_used);
        for (unsigned i = 0; i < lanes_used; ++i) streams[i] = fragment(lanes[i], widths[i], 0);
        return interleave(streams, widths, lanes_used, lanes[0].size());
    }
};

bool same_bytes(const std::vector<unsigned char>& got, const unsigned char* want, std::size_t size) {
    return got.size() == size && std::memcmp(got.data(), want, size) == 0;
}

void test_bcpack_vectors() {
    using palmetto::dstorage::bcpack::DecodeError;
    std::string failure;
    for (const EncoderVector& vector : kEncoderVectors) {
        const unsigned lanes_used = vector.codec >= 6 ? 16u : 12u;
        const std::size_t elements = vector.blocks * (vector.codec == 1 || vector.codec == 4 ? 1u : 2u);
        std::vector<std::vector<unsigned>> lanes(lanes_used);
        for (unsigned lane = 0; lane < lanes_used; ++lane)
            lanes[lane].assign(vector.symbols + lane * elements, vector.symbols + (lane + 1) * elements);
        const std::vector<unsigned char> encoded = TestEncoder::encode(lanes, vector.codec);
        const std::string what = "bcpack: codec " + std::to_string(vector.codec) + ", " +
                                 std::to_string(vector.blocks) + " block(s) ";
        if (!same_bytes(encoded, vector.source, vector.source_size)) {
            check(false, what + "encoder reproduces the reference chunk");
            continue;
        }
        check(true, what + "encoder reproduces the reference chunk");
        std::vector<unsigned char> destination(vector.expected_size);
        palmetto::dstorage::bcpack::DecodeStats stats;
        const auto error = palmetto::dstorage::bcpack::decode(vector.codec, encoded.data(), encoded.size(),
                                                              destination.data(), destination.size(), nullptr, &stats);
        check(error == DecodeError::ok && same_bytes(destination, vector.expected, vector.expected_size) &&
                  stats.blocks == vector.blocks,
              what + "decodes to the reference blocks");
        std::vector<unsigned char> from_reference(vector.expected_size);
        const auto reference = palmetto::dstorage::bcpack::decode(
            vector.codec, vector.source, vector.source_size, from_reference.data(), from_reference.size(), nullptr,
            nullptr);
        check(reference == DecodeError::ok &&
                  same_bytes(from_reference, vector.expected, vector.expected_size),
              what + "reference chunk decodes to the reference blocks");
    }
    (void)failure;
}

