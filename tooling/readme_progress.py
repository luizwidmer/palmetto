"""Render the README's progress tracker from docs/progress.json.

The tracker is generated rather than typed so it cannot drift from the measurements: the facts live in one JSON file, the
README carries only the rendered block between the two markers below, and `--check` fails when the two disagree (a
pre-commit hook or CI can run it).

    python -I tooling/readme_progress.py                 rewrite the block in README.md
    python -I tooling/readme_progress.py --check         exit 1 when README.md is out of date
    python -I tooling/readme_progress.py --stdout        print the block and write nothing

Only counts, states, error classes and the project's own document text go in the block - never a path into a game copy,
a shader name or an extracted file.
"""
import argparse
import json
import os
import re
import sys

BEGIN = "<!-- progress:begin -->"
END = "<!-- progress:end -->"
STATE_MARK = {"done": "**done**", "in progress": "in progress", "not reached": "not reached"}


def load(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def check_facts(facts):
    """Refuse anything that looks like it came from the game copy rather than from a measurement."""
    text = json.dumps(facts)
    forbidden = ("/local package", "game console", "F:\\\\", "D:\\\\", "\\\\\\\\", ".arc", "shaders.arc")
    for marker in forbidden:
        if marker in text:
            raise SystemExit(f"progress facts contain {marker!r}: keep paths and file names out of the tracker")


def render(facts):
    lines = [BEGIN]
    lines.append("<!-- Generated by tooling/readme_progress.py from docs/progress.json. Do not edit by hand. -->")
    lines.append("")
    commit = facts.get("commit", "")
    at = f" at `{commit}`" if re.fullmatch(r"[0-9a-f]{7,40}", commit or "") else ""
    lines.append(f"*Last updated {facts['updated']}{at}.* {facts['intro']}")
    lines.append("")

    lines.append("| Stage | State | What backs that |")
    lines.append("|---|---|---|")
    for row in facts["stages"]:
        lines.append(f"| {row['stage']} | {STATE_MARK.get(row['state'], row['state'])} | {row['evidence']} |")
    lines.append("")

    lines.append("| Measured | Value |")
    lines.append("|---|---|")
    for row in facts["counts"]:
        lines.append(f"| {row['what']} | {row['value']} |")
    lines.append("")

    frontier = facts["frontier"]
    lines.append(f"**Where it stops now:** `{frontier['stop']}` - {frontier['summary']}")
    lines.append(f"Measurements and the method behind them: [{frontier['detail_doc']}]({frontier['detail_doc']}).")
    lines.append("")

    lines.append("Next up:")
    for item in facts["next"]:
        lines.append(f"- {item}")
    lines.append("")

    if facts.get("links"):
        lines.append("More: " + ", ".join(f"[{row['what']}]({row['where']})" for row in facts["links"]) + ".")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replace_block(readme, block):
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"README.md has no {BEGIN} ... {END} pair to fill")
    return readme[:start] + block + readme[end + len(END):]


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--facts", default=os.path.join(here, "docs", "progress.json"))
    parser.add_argument("--readme", default=os.path.join(here, "README.md"))
    parser.add_argument("--check", action="store_true", help="exit 1 when the README block is out of date")
    parser.add_argument("--stdout", action="store_true", help="print the rendered block, write nothing")
    args = parser.parse_args()

    facts = load(args.facts)
    check_facts(facts)
    block = render(facts)

    if args.stdout:
        sys.stdout.write(block + "\n")
        return 0

    with open(args.readme, encoding="utf-8", newline="") as handle:
        readme = handle.read()
    updated = replace_block(readme, block)

    if updated == readme:
        print("README progress tracker is up to date")
        return 0
    if args.check:
        print("README progress tracker is out of date; run: python -I tooling/readme_progress.py", file=sys.stderr)
        return 1
    with open(args.readme, "w", encoding="utf-8", newline="") as handle:
        handle.write(updated)
    print("README progress tracker updated")
    return 0


if __name__ == "__main__":
    try:  # a redirected stdout is strict ANSI code page under -I; write '?' for what it cannot encode
        sys.stdout.reconfigure(errors="replace")
    except (AttributeError, ValueError, OSError):
        pass
    sys.exit(main())
